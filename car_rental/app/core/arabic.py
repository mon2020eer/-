# -*- coding: utf-8 -*-
"""صياغة الأعداد بالعربية صياغةً سليمة.

العربية تميّز المفرد والمثنّى وجمع القلّة (3–10) وجمع الكثرة (11 فأكثر)،
وتجاهل ذلك يُنتج «6 ساعة» و«2 يوم» و«تبقّى 3 يوم» — وهو ركيك في برنامج
يقرؤه صاحب مكتب كل يوم وفي عقد يوقّعه عميل.

الوحدة **صافية** (pure): لا تستورد شيئاً، فتصلح لكل الطبقات بلا دوران استيراد.
"""


def count(number, one, two, few, many):
    """يصوغ العدد مع تمييزه الصحيح.

    >>> count(6, "ساعة واحدة", "ساعتان", "ساعات", "ساعة")
    '6 ساعات'
    >>> count(1, "يوم واحد", "يومان", "أيام", "يوماً")
    'يوم واحد'
    """
    number = int(number or 0)
    if number == 1:
        return one
    if number == 2:
        return two
    if 3 <= number % 100 <= 10:
        return "%d %s" % (number, few)
    return "%d %s" % (number, many)


def days(number):
    """«يوم واحد» · «يومان» · «5 أيام» · «12 يوماً»."""
    return count(number, "يوم واحد", "يومان", "أيام", "يوماً")


def hours(number):
    """«ساعة واحدة» · «ساعتان» · «5 ساعات» · «12 ساعة»."""
    return count(number, "ساعة واحدة", "ساعتان", "ساعات", "ساعة")
